// Generate minimal valid MP4 (requires ffmpeg, so we'll create instructions instead)
function generateVideoInstructions() {
  const instructions = `
# To generate test-video.mp4, run one of these commands:

# Option 1: Using ffmpeg (recommended)
ffmpeg -f lavfi -i color=c=blue:s=320x240:d=1 -c:v libx264 -pix_fmt yuv420p e2e/fixtures/test-video.mp4

# Option 2: Copy any short video file you have
# Just copy any MP4 file to: e2e/fixtures/test-video.mp4

# Note: The E2E tests will skip video tests if test-video.mp4 is not present
`;
  
  const instructionsPath = path.join(fixturesDir, 'VIDEO_SETUP.txt');
  fs.writeFileSync(instructionsPath, instructions);
  console.log('ℹ Created VIDEO_SETUP.txt with instructions for creating test video');
  console.log('  (Video file requires ffmpeg or manual file copy)');
}

// Generate all fixtures
function generateAll() {
  console.log('Generating test fixtures...\n');
  
  try {
    generateTestPNG();
    generateTestJPEG();
    generateVideoInstructions();
    
    console.log('\n✓ Test fixtures generated successfully!');
    console.log('\nGenerated files:');
    console.log('  - e2e/fixtures/test-image.png');
    console.log('  - e2e/fixtures/test-image.jpg');
    console.log('  - e2e/fixtures/VIDEO_SETUP.txt (instructions)');
    console.log('\nNote: You need to manually create test-video.mp4 using ffmpeg or copy a test video.');
  } catch (error) {
    console.error('Error generating fixtures:', error);
    process.exit(1);
  }
}

generateAll();
